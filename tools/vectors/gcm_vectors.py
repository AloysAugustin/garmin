#!/usr/bin/env python3
"""Generate AES-128-GCM test vectors for source/tests/GcmVectors.mc.

Every vector is computed with two independent libraries (pyca/cryptography,
which wraps OpenSSL, and PyCryptodome) and must agree with both, plus the
AES-128 test cases 1-4 from McGrew & Viega, "The Galois/Counter Mode of
Operation (GCM)" (the vectors NIST published with SP 800-38D).

Usage: python3 -I tools/vectors/gcm_vectors.py > source/tests/GcmVectors.mc
Needs: pip install cryptography pycryptodome
"""
import random

from Crypto.Cipher import AES
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

# (key, iv, plaintext, aad, ciphertext, tag) - McGrew & Viega test cases 1-4.
P3 = ("d9313225f88406e5a55909c5aff5269a86a7a9531534f7da2e4c303d8a318a72"
      "1c3c0c95956809532fcf0e2449a6b525b16aedf5aa0de657ba637b391aafd255")
C3 = ("42831ec2217774244b7221b784d0d49ce3aa212f2c02a4e035c17e2329aca12e"
      "21d514b25466931c7d8f6a5aac84aa051ba30b396a0aac973d58e091473f5985")
NIST = [
    ("00000000000000000000000000000000", "000000000000000000000000", "", "",
     "", "58e2fccefa7e3061367f1d57a4e7455a"),
    ("00000000000000000000000000000000", "000000000000000000000000",
     "00000000000000000000000000000000", "",
     "0388dace60b6a392f328c2b971b2fe78", "ab6e47d42cec13bdf53a67b21257bddf"),
    ("feffe9928665731c6d6a8f9467308308", "cafebabefacedbaddecaf888", P3, "",
     C3, "4d5c2af327cd64a62cf35abd2ba6fab4"),
    ("feffe9928665731c6d6a8f9467308308", "cafebabefacedbaddecaf888", P3[:120],
     "feedfacedeadbeeffeedfacedeadbeefabaddad2",
     C3[:120], "5bc94fbc3221a5db94fae95ae7121a47"),
]


def seal_both(key, iv, pt, aad):
    a = AESGCM(key).encrypt(iv, pt, aad or None)
    c = AES.new(key, AES.MODE_GCM, nonce=iv)
    c.update(aad)
    ct, tag = c.encrypt_and_digest(pt)
    assert a == ct + tag, "cryptography and PyCryptodome disagree"
    return ct, tag


def main():
    vectors = []
    for k, iv, p, a, c, t in NIST:
        ct, tag = seal_both(bytes.fromhex(k), bytes.fromhex(iv), bytes.fromhex(p), bytes.fromhex(a))
        assert ct.hex() == c and tag.hex() == t, "library disagrees with published vector"
        vectors.append((k, iv, p, a, c, t))
    # Seeded random cases: every length around the block boundaries, with no
    # AAD, short AAD and the 32-byte SHA-256 AAD the Tesla protocol uses.
    rng = random.Random(20261026)
    for n in [0, 1, 2, 6, 15, 16, 17, 31, 32, 33, 47, 48, 64, 100]:
        for alen in [0, 13, 32]:
            key, iv = rng.randbytes(16), rng.randbytes(12)
            pt, aad = rng.randbytes(n), rng.randbytes(alen)
            ct, tag = seal_both(key, iv, pt, aad)
            vectors.append((key.hex(), iv.hex(), pt.hex(), aad.hex(), ct.hex(), tag.hex()))

    print("// Generated by tools/vectors/gcm_vectors.py - do not edit.")
    print("// AES-128-GCM vectors: McGrew & Viega test cases 1-4, then seeded random")
    print("// cases, each checked against pyca/cryptography and PyCryptodome.")
    print("(:test)")
    print("module GcmVectors {")
    print("    // [key, iv, plaintext, aad, ciphertext, tag] (hex)")
    print("    const VECTORS = [")
    for v in vectors:
        print("        [" + ", ".join('"%s"' % x for x in v) + "],")
    print("    ];")
    print("}")


if __name__ == "__main__":
    main()
